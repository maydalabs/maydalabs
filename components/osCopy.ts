/* MaydaOS, client-facing.
 *
 * Every value here is a plain string, including the ones with numbers in
 * them: this object crosses into a client component, and a function cannot
 * make that trip. */

export function fillBudget(template: string, spent: string, budget: string): string {
  return template.replace("{spent}", spent).replace("{budget}", budget);
}

